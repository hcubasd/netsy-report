import { generatePalettes } from 'nicrainha';
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Two categorical colours distinguish the two classifications; no continuous
// quantity is encoded in this figure. Exact library RGB output, no manual tint.
const specification = { size: 2, lightness: 90, rotation: 17 };
const colours = generatePalettes(specification.size, {
  lightness: specification.lightness,
})[specification.rotation];
const names = ['functionalView', 'academicView'];
const path = relative => fileURLToPath(new URL(relative, import.meta.url));
const version = JSON.parse(readFileSync(path('./node_modules/nicrainha/package.json'))).version;
const tex = '% Generated by analysis/generate-palette.mjs; do not edit RGB values.\n'
  + colours.map(({ r, g, b }, i) => `\\definecolor{${names[i]}}{RGB}{${r},${g},${b}}`).join('\n') + '\n';
writeFileSync(path('../figures/palette.tex'), tex);
writeFileSync(path('../results/palette.json'), JSON.stringify({
  generator: 'nicrainha', version, specification,
  purpose: 'Categorical distinction between functional and academic classifications',
  colours: Object.fromEntries(names.map((name, i) => [name, colours[i]])),
}, null, 2) + '\n');
